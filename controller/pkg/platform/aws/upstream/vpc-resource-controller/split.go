// Splits the rendered VPC resource controller: the Deployment, which the
// controller adapts with each cluster's facts, and everything else, which the
// product chart ships as written behind its Windows IPAM gate.
package main

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"strings"

	"sigs.k8s.io/yaml"
)

func main() {
	raw, err := io.ReadAll(os.Stdin)
	if err != nil {
		panic(err)
	}
	var deployment, static bytes.Buffer
	for _, doc := range strings.Split(string(raw), "\n---\n") {
		doc = strings.TrimPrefix(strings.TrimSpace(doc), "---\n")
		if doc == "" {
			continue
		}
		var head struct{ Kind string }
		if err := yaml.Unmarshal([]byte(doc), &head); err != nil {
			panic(err)
		}
		if head.Kind == "Deployment" {
			fmt.Fprintf(&deployment, "%s\n", doc)
			continue
		}
		fmt.Fprintf(&static, "---\n%s\n", doc)
	}
	if err := os.WriteFile(os.Args[1], deployment.Bytes(), 0o644); err != nil {
		panic(err)
	}
	chart := "{{- if .Values.platforms.aws.vpcCNI.windows.ipamImage }}\n" +
		"{{- /*\nGenerated by controller/pkg/platform/aws/upstream/vpc-resource-controller/render.sh\n" +
		"from AWS's VPC resource controller ca7792b (config/default) with the product's\n" +
		"webhook scoping; the controller applies its Deployment with the cluster's facts.\n*/}}\n" +
		static.String() + "{{- end }}\n"
	if err := os.WriteFile(os.Args[2], []byte(chart), 0o644); err != nil {
		panic(err)
	}
}
